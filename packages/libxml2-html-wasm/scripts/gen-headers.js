// Generate include/libxml/xmlversion.h and config.h for a libxml2 source tree.
//
// configure would produce both; running autotools on Windows is a dead end, and
// their only role here is @VAR@ substitution plus a handful of HAVE_* defines.
//
// Usage: node gen-headers.js <path-to-libxml2-source>
import fs from "node:fs";
import path from "node:path";
import process from "node:process";

const SRC = process.argv[2];
if (!SRC) {
  console.error("usage: node gen-headers.js <libxml2-source-dir>");
  process.exit(1);
}

const inFile = path.join(SRC, "include", "libxml", "xmlversion.h.in");
const outFile = path.join(SRC, "include", "libxml", "xmlversion.h");

const VERSION = "2.11.9";
const VERSION_NUMBER = "21109";

const FEATURES = {
  WITH_C14N: 1,
  WITH_CATALOG: 1,
  WITH_DEBUG: 0,
  WITH_FTP: 0,
  WITH_HTML: 1, // the whole point
  WITH_HTTP: 0,
  WITH_ICONV: 0,
  WITH_ICU: 0,
  WITH_ISO8859X: 1,
  WITH_LEGACY: 1,
  WITH_LZMA: 0,
  WITH_MEM_DEBUG: 0,
  WITH_MODULES: 0,
  WITH_OUTPUT: 1,
  WITH_PATTERN: 1,
  WITH_PUSH: 1,
  WITH_READER: 1,
  WITH_REGEXPS: 1,
  WITH_SAX1: 1,
  WITH_SCHEMAS: 1,
  WITH_SCHEMATRON: 0,
  WITH_THREAD_ALLOC: 0,
  WITH_THREADS: 0,
  WITH_TREE: 1,
  WITH_TRIO: 0,
  WITH_VALID: 1,
  WITH_WRITER: 1,
  WITH_XINCLUDE: 1,
  WITH_XPATH: 1,
  WITH_XPTR: 1,
  WITH_XPTR_LOCS: 1,
  WITH_ZLIB: 0,
};

let text = fs.readFileSync(inFile, "utf8");
let replaced = 0;

text = text.replace(/@([A-Z0-9_]+)@/g, (match, name) => {
  replaced++;
  if (name === "VERSION") return VERSION;
  if (name === "LIBXML_VERSION_NUMBER") return VERSION_NUMBER;
  if (name === "LIBXML_VERSION_EXTRA") return "";
  if (name === "MODULE_EXTENSION") return ".wasm";
  if (name in FEATURES) return String(FEATURES[name]);
  throw new Error(`unhandled substitution: @${name}@ in ${inFile}`);
});

const leftover = text.match(/@[A-Z0-9_]+@/g);
if (leftover) throw new Error(`unsubstituted: ${[...new Set(leftover)].join(", ")}`);

fs.writeFileSync(outFile, text);
console.log(`wrote ${outFile} (${replaced} substitutions)`);

// libxml2's internal libxml.h includes "config.h" unconditionally. Only true
// HAVE_* defines belong here: libxml2 tests them with #ifdef, so defining a
// feature as 0 would wrongly enable it.
const CONFIG_H = `/* generated by gen-headers.js for emscripten/wasm32 */
#ifndef LIBXML_CONFIG_H
#define LIBXML_CONFIG_H

#define HAVE_CTYPE_H 1
#define HAVE_ERRNO_H 1
#define HAVE_FCNTL_H 1
#define HAVE_INTTYPES_H 1
#define HAVE_LIMITS_H 1
#define HAVE_LOCALE_H 1
#define HAVE_MATH_H 1
#define HAVE_MEMORY_H 1
#define HAVE_SIGNAL_H 1
#define HAVE_STDINT_H 1
#define HAVE_STDLIB_H 1
#define HAVE_STRING_H 1
#define HAVE_STRINGS_H 1
#define HAVE_SYS_STAT_H 1
#define HAVE_SYS_TIME_H 1
#define HAVE_SYS_TYPES_H 1
#define HAVE_TIME_H 1
#define HAVE_UNISTD_H 1

#define HAVE_GETTIMEOFDAY 1
#define HAVE_ISASCII 1
#define HAVE_ISINF 1
#define HAVE_ISNAN 1
#define HAVE_SNPRINTF 1
#define HAVE_STRFTIME 1
#define HAVE_VA_COPY 1
#define HAVE___VA_COPY 1
#define HAVE_VSNPRINTF 1

#define STDC_HEADERS 1

#endif
`;

fs.writeFileSync(path.join(SRC, "config.h"), CONFIG_H);
console.log(`wrote ${path.join(SRC, "config.h")}`);
